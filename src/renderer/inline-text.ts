/**
 * 把一段 Markdown **行内**语法变成"看起来的样子"（纯文本）。
 *
 * 用途只有一个：那些**不能被渲染、只能显示成文字**的地方 —— 目前是大纲列表
 * （侧栏一条标题 = 一行纯文本，塞不进 `<strong>`/`<em>` 的语义）。
 * Typora 的大纲也是这么干的：`### **1. 结论**` 在侧栏里显示成「1. 结论」，
 * 星号不会跟着跑到侧栏上去。
 *
 * 三条硬约束：
 *   1. **只做减法，不做格式化**：除了去掉标记字符，一个字符都不改写、不重排。
 *   2. **字符偏移不重要**：这里产出的是"给人看的字符串"，不参与任何位置计算，
 *      所以可以放心替换（渲染层的隐藏标记走的是另一套，那边靠区间，见 markers.ts）。
 *   3. **反斜杠转义要还原**：`\*不是斜体\*` 显示成 `*不是斜体*`，不能把反斜杠也留下。
 */

export function plainInlineMarkdown(src: string): string {
  if (!src) return ''

  // ① 先把转义字符抽走占位：否则 `\*` 会被后面对斜体的处理当成标记吃掉。
  const escaped: string[] = []
  let s = src.replace(/\\([\\`*_{}\[\]()#+\-.!~=|>])/g, (_m, ch: string) => {
    escaped.push(ch)
    return `\u0000${escaped.length - 1}\u0000`
  })

  // ② 行内代码整段先拿出来：里面的星号/下划线是字面量，不该参与加粗斜体判断。
  const codes: string[] = []
  s = s.replace(/`+([^`]*)`+/g, (_m, body: string) => {
    codes.push(body)
    return `\u0001${codes.length - 1}\u0001`
  })

  // ③ 图片 / 链接 / 脚注引用：只留可见的那部分文字
  s = s.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
  s = s.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
  s = s.replace(/\[\^[^\]]*\]/g, '')

  // ④ HTML 注释整段不要；其余标签只留内容（`<u>x</u>`、`<sub>2</sub>`…）
  s = s.replace(/<!--[\s\S]*?-->/g, '')
  s = s.replace(/<\/?[A-Za-z][^>]*>/g, '')

  // ⑤ 强调标记：成对才删，且要求"标记内侧不是空格"（与 markers.ts 的规则一致，
  //    否则 `a * b * c` 这种算式会被误吃）。先长后短：`**` 必须在 `*` 之前。
  // 每一档都要求「外层不是同一个字符」：否则 `a ** b ** c` 会先被 `*` 那一档
  // 从 `**` 里各咬走一个星号，变成 `a * b * c`（星号数变了，属于改了内容）。
  s = s.replace(/(?<![*_])\*\*\*(?=\S)([\s\S]*?\S)\*\*\*(?!\*)/g, '$1')
  s = s.replace(/(?<![*_])(\*\*)(?=\S)([\s\S]*?\S)\1(?!\*)/g, '$2')
  s = s.replace(/(?<!_)(__)(?=\S)([\s\S]*?\S)\1(?!_)/g, '$2')
  s = s.replace(/~~(?=\S)([\s\S]*?\S)~~/g, '$1')
  s = s.replace(/==(?=\S)([\s\S]*?\S)==/g, '$1')
  s = s.replace(/(?<!\*)(\*)(?=[^\s*])([\s\S]*?[^\s*])\1(?!\*)/g, '$2')
  // `_` 额外要求左边不是 \w：`foo_bar_baz` 是标识符，不是斜体
  s = s.replace(/(?<![\w_])(_)(?=[^\s_])([\s\S]*?[^\s_])\1(?!_)/g, '$2')

  // ⑥ 先归一空白（占位符里没有空白，不怕被压），再把代码与转义字符原样放回 ——
  //    反过来的话，代码段里的连续空格会被这一步压成一个。
  s = s.replace(/\s+/g, ' ').trim()
  s = s.replace(/\u0001(\d+)\u0001/g, (_m, i: string) => codes[Number(i)] ?? '')
  s = s.replace(/\u0000(\d+)\u0000/g, (_m, i: string) => escaped[Number(i)] ?? '')
  return s
}
